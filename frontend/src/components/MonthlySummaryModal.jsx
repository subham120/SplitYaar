import { useState } from 'react';
import { X, Copy, Check, FileSpreadsheet, MessageCircle } from 'lucide-react';
import { formatCurrency } from '../lib/formatters';

export default function MonthlySummaryModal({ trip, members, expenses, balances, onClose }) {
  const [copied, setCopied] = useState(false);

  if (!trip || !members || !expenses) return null;

  // Group expenses by month
  const byMonth = {};
  expenses.forEach((exp) => {
    const month = exp.date.slice(0, 7); // YYYY-MM
    if (!byMonth[month]) byMonth[month] = [];
    byMonth[month].push(exp);
  });

  const getMemberName = (id) => members.find((m) => m._id === id)?.name || 'Unknown';

  // Build WhatsApp-friendly summary
  const buildSummary = () => {
    let text = `*SplitYaar — ${trip.name}*\n`;
    text += `Group Code: ${trip.code}\n\n`;

    const totalPaise = expenses.reduce((s, e) => s + e.amountPaise, 0);
    text += `*Total Spent:* ${formatCurrency(totalPaise)}\n`;
    text += `*Members:* ${members.length}\n\n`;

    text += `*— Member Balances —*\n`;
    balances?.forEach((b) => {
      const name = getMemberName(b.memberId);
      const net = b.netBalancePaise;
      const statusSymbol = net > 0 ? '[+]' : net < 0 ? '[-]' : '[=]';
      text += `${statusSymbol} ${name}: ${net >= 0 ? '+' : ''}${formatCurrency(net)}\n`;
    });

    text += `\n_Generated by SplitYaar_`;
    return text;
  };

  const summary = buildSummary();

  const handleCopy = async () => {
    await navigator.clipboard.writeText(summary);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleWhatsApp = () => {
    window.open(`https://wa.me/?text=${encodeURIComponent(summary)}`, '_blank');
  };

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal-content" onClick={(e) => e.stopPropagation()}>
        <div className="flex items-center justify-between p-4 border-b border-divider-soft">
          <h3 className="text-lg font-semibold text-ink m-0 flex items-center gap-2">
            <FileSpreadsheet size={18} className="text-[#0071e3]" />
            <span>Summary</span>
          </h3>
          <button
            onClick={onClose}
            className="p-1.5 rounded-full hover:bg-canvas-parchment transition-colors"
            style={{ background: 'none', border: 'none', cursor: 'pointer' }}
          >
            <X size={18} />
          </button>
        </div>

        <div className="p-4">
          <pre className="text-xs text-ink-muted-80 whitespace-pre-wrap bg-canvas-parchment rounded-md p-3 m-0 max-h-64 overflow-y-auto" style={{ fontFamily: 'inherit' }}>
            {summary}
          </pre>
        </div>

        <div className="flex gap-2 p-4 pt-0">
          <button onClick={handleCopy} className="btn-secondary flex-1">
            {copied ? <Check size={14} /> : <Copy size={14} />}
            {copied ? 'Copied!' : 'Copy'}
          </button>
          <button onClick={handleWhatsApp} className="btn-primary flex-1 inline-flex items-center justify-center gap-2">
            <MessageCircle size={15} />
            <span>WhatsApp</span>
          </button>
        </div>
      </div>
    </div>
  );
}
